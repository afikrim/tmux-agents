import {installBridge,toolTarget,toolDetail} from '../plugins/opencode-tmux-agents/bridge.mjs';
import assert from 'node:assert/strict';
let active = 'a', reports = [], handlers = {}, cleaned = 0;
const context = {ui: {router: {current: () => active ? {type:'session', sessionID:active} : {type:'home'}}},
  data: {on: (event, fn) => {handlers[event] = fn; return () => cleaned++;}}};
const stop = installBridge(context, (...args) => reports.push(args));
handlers['permission.asked']({data:{sessionID:'b'}});
assert.equal(reports.length,0);
handlers['permission.asked']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['PermissionRequest','a']);
handlers['form.created']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['FormCreated','a']);
handlers['session.status']({properties:{sessionID:'a',status:{type:'busy'}}});
handlers['session.next.reasoning.started']({properties:{sessionID:'a'}});
handlers['session.idle']({data:{sessionID:'a'}});
assert.equal(reports.length,0); // activity/idle cannot acknowledge an unanswered question
handlers['form.replied']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['PostToolUse','a']);
handlers['session.idle']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['Stop','a']);
active = null;
handlers['permission.asked']({data:{sessionID:'a'}});
assert.equal(reports.length,0);
active = 'b';
handlers['session.execution.started']({data:{sessionID:'b'}});
assert.deepEqual(reports.pop(),['UserPromptSubmit','b']);
handlers['session.tool.input.started.1']({data:{sessionID:'b',id:'1',name:'bash'}});
handlers['session.tool.called.1']({data:{sessionID:'b',id:'1',input:{secret:'never forward'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','bash']);
handlers['session.tool.input.started']({data:{sessionID:'b',id:'2',name:'read'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'2'}});
assert.deepEqual(reports.pop(),['PreToolUse','b','read']);
handlers['session.tool.success.2']({data:{sessionID:'b',id:'2',content:['private output']}});
assert.deepEqual(reports.pop(),['PreToolUse','b','bash']);
handlers['session.tool.failed.2']({data:{sessionID:'b',id:'1'}});
assert.deepEqual(reports.pop(),['PostToolUseFailure','b','bash','','']);
handlers['session.tool.called']({data:{sessionID:'foreign',id:'other'}});
assert.equal(reports.length,0);
handlers['session.tool.input.started']({data:{sessionID:'b',id:'orphan',name:'edit'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'orphan'}});
reports.pop();
handlers['session.idle']({data:{sessionID:'b'}});
assert.deepEqual(reports.pop(),['Stop','b']);
handlers['session.tool.success.2']({data:{sessionID:'b',id:'late'}});
assert.equal(reports.length,0);
assert.equal(toolTarget('edit',{filePath:'/private/project/app.py',oldString:'secret'}),'app.py');
assert.equal(toolTarget('read',JSON.stringify({file_path:'C:\\code\\README.md'})),'README.md');
assert.equal(toolTarget('bash',{filePath:'/secret',command:'secret'}),'');
assert.equal(toolTarget('edit',{filePath:'evil\u001b.py'}),'');
assert.equal(toolTarget('edit',{filePath:'https://host/key?secret'}),'');
assert.equal(toolTarget('apply_patch',{input:'*** Begin Patch\n*** Update File: /src/app.py\n@@\n+secret\n*** End Patch'}),'app.py');
handlers['session.tool.input.started']({data:{sessionID:'b',id:'e',name:'edit'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'e',input:{filePath:'/private/app.py',oldString:'SECRET BODY'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','edit','app.py']);
handlers['session.tool.input.started']({data:{sessionID:'b',id:'r',name:'read'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'r',input:{filePath:'/private/README.md'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','read','README.md']);
handlers['session.tool.success']({data:{sessionID:'b',id:'r',content:'SECRET OUTPUT'}});
assert.deepEqual(reports.pop(),['PreToolUse','b','edit','app.py']);
handlers['session.tool.success']({data:{sessionID:'b',id:'e'}});
assert.deepEqual(reports.pop(),['PostToolUse','b','edit','app.py']);
handlers['session.tool.called']({data:{sessionID:'a',id:'foreign',input:{filePath:'/private/foreign.py'}}});
assert.equal(reports.length,0);
// Current SDK event names, call IDs, direct tool names and event envelopes.
handlers['session.next.tool.called.1']({data:{sessionID:'b',callID:'current',tool:'bash',input:{description:'Run regression tests',command:'pytest --token SECRET'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','bash','','Run regression tests']);
handlers['session.next.tool.success.1']({data:{sessionID:'b',callID:'current',content:'SECRET OUTPUT'}});
assert.deepEqual(reports.pop(),['PostToolUse','b','bash','','Run regression tests']);
handlers['session.next.tool.called']({properties:{sessionID:'b',callID:'mcp',tool:'mcp__github__create_pull_request',input:{body:'SECRET BODY'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','mcp__github__create_pull_request']);
handlers['session.next.tool.success']({properties:{sessionID:'b',callID:'mcp'}});
assert.deepEqual(reports.pop(),['PostToolUse','b','mcp__github__create_pull_request']);
handlers['session.next.compaction.started']({properties:{sessionID:'b'}});
assert.deepEqual(reports.pop(),['PreCompact','b']);
handlers['session.next.text.started.1']({data:{sessionID:'b',text:'NEVER READ'}});
assert.deepEqual(reports.pop(),['ResponseStarted','b']);
handlers['session.status']({properties:{sessionID:'b',status:{type:'retry',error:'SECRET ERROR'}}});
assert.deepEqual(reports.pop(),['Retrying','b']);
assert.equal(toolDetail('mcp__github__create_issue',{description:'PRIVATE ISSUE BODY'}),'');
assert.equal(toolDetail('bash',{description:'Run tests'}),'Run tests');
assert.equal(toolDetail('bash',{description:'Read /private/secrets'}),'');
assert.equal(toolDetail('webfetch',{url:'https://user:password@example.com/private?token=secret'}),'example.com');
stop(); assert.equal(cleaned,Object.keys(handlers).length);
console.log('OpenCode session isolation and lifecycle passed');
