import {installBridge} from '../plugins/opencode-tmux-agents/bridge.mjs';
import assert from 'node:assert/strict';
let active = 'a', reports = [], handlers = {}, cleaned = 0;
const context = {ui: {router: {current: () => active ? {type:'session', sessionID:active} : {type:'home'}}},
  data: {on: (event, fn) => {handlers[event] = fn; return () => cleaned++;}}};
const stop = installBridge(context, (...args) => reports.push(args));
handlers['permission.asked']({data:{sessionID:'b'}});
assert.equal(reports.length,0);
handlers['permission.asked']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['PermissionRequest','a']);
handlers['form.created']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['FormCreated','a']);
handlers['session.idle']({data:{sessionID:'a'}});
assert.deepEqual(reports.pop(),['Stop','a']);
active = null;
handlers['permission.asked']({data:{sessionID:'a'}});
assert.equal(reports.length,0);
active = 'b';
handlers['session.execution.started']({data:{sessionID:'b'}});
assert.deepEqual(reports.pop(),['UserPromptSubmit','b']);
handlers['session.tool.input.started.1']({data:{sessionID:'b',id:'1',name:'bash'}});
handlers['session.tool.called.1']({data:{sessionID:'b',id:'1',input:{secret:'never forward'}}});
assert.deepEqual(reports.pop(),['PreToolUse','b','bash']);
handlers['session.tool.input.started']({data:{sessionID:'b',id:'2',name:'read'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'2'}});
assert.deepEqual(reports.pop(),['PreToolUse','b','read']);
handlers['session.tool.success.2']({data:{sessionID:'b',id:'2',content:['private output']}});
assert.deepEqual(reports.pop(),['PreToolUse','b','bash']);
handlers['session.tool.failed.2']({data:{sessionID:'b',id:'1'}});
assert.deepEqual(reports.pop(),['PostToolUse','b']);
handlers['session.tool.called']({data:{sessionID:'foreign',id:'other'}});
assert.equal(reports.length,0);
handlers['session.tool.input.started']({data:{sessionID:'b',id:'orphan',name:'edit'}});
handlers['session.tool.called']({data:{sessionID:'b',id:'orphan'}});
reports.pop();
handlers['session.idle']({data:{sessionID:'b'}});
assert.deepEqual(reports.pop(),['Stop','b']);
handlers['session.tool.success.2']({data:{sessionID:'b',id:'late'}});
assert.equal(reports.length,0);
stop(); assert.equal(cleaned,Object.keys(handlers).length);
console.log('OpenCode session isolation and lifecycle passed');
